-- 금전출납부. 잔고는 저장하지 않고 화면에서 일자·id 순으로 누적해 계산한다(줄을 고치면 뒤 잔고가 자동으로 따라온다).
CREATE TABLE cash_ledger_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    entry_date date NOT NULL,
    memo character varying(200) NOT NULL DEFAULT '',
    cash_in bigint NOT NULL DEFAULT 0,
    card_in bigint NOT NULL DEFAULT 0,
    expense bigint NOT NULL DEFAULT 0,
    etc character varying(200) NOT NULL DEFAULT '',
    CONSTRAINT cash_ledger_entry_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_cash_ledger_entry_date ON cash_ledger_entry (entry_date, id);
