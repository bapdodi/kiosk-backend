-- 관리자 AI 도우미 질문·답 기록. 이상한 답이 나왔을 때 확인하려고 남기고 30일 뒤 지운다(AssistantService).
CREATE TABLE assistant_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp NOT NULL,
    question text NOT NULL,
    tools character varying(1000) NOT NULL DEFAULT '',
    answer text NOT NULL,
    CONSTRAINT assistant_log_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_assistant_log_created_at ON assistant_log (created_at);
