-- 거래명세서 자동 입력이 사람의 확정/수정에서 배우는 짝. 명세서 품명과 ERP 품명이 달라서 필요하다.
-- name_key 는 품명의 영문/한글/숫자 토큰을 정렬해 붙인 값이다(OCR 손글씨 잡음에 덜 흔들린다).
CREATE TABLE statement_item_alias (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    vendor_code integer NOT NULL,
    name_key character varying(200) NOT NULL,
    item_code integer NOT NULL,
    hits integer NOT NULL DEFAULT 1,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT statement_item_alias_pkey PRIMARY KEY (id),
    CONSTRAINT uk_statement_item_alias UNIQUE (vendor_code, name_key, item_code)
);

CREATE INDEX idx_statement_item_alias_vendor ON statement_item_alias (vendor_code);

-- 명세서의 공급자 사업자번호(숫자만) → ERP 거래처. GURAE.SAUP 은 매입처 172곳 중 6곳만 채워져 있다.
CREATE TABLE statement_vendor_alias (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    biz_no character varying(20) NOT NULL,
    vendor_code integer NOT NULL,
    hits integer NOT NULL DEFAULT 1,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT statement_vendor_alias_pkey PRIMARY KEY (id),
    CONSTRAINT uk_statement_vendor_alias UNIQUE (biz_no, vendor_code)
);
