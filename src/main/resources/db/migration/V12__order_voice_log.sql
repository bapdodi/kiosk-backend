-- 손님용 AI 음성 통화(주문) 기록. 통화 내역, 인식된 말, 도구 호출, 발생 오류를 보관한다.
CREATE TABLE order_voice_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp NOT NULL,
    session_id varchar(64),
    customer_name varchar(255),
    status varchar(50) NOT NULL DEFAULT 'completed',
    transcript text NOT NULL DEFAULT '',
    tools text NOT NULL DEFAULT '',
    error_message text,
    order_id bigint,
    CONSTRAINT order_voice_log_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_order_voice_log_created_at ON order_voice_log (created_at);
